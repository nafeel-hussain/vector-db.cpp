using Clock = std::chrono::high_resolution_clock;

BenchmarkRunner::BenchmarkRunner(const std::string& outputMarkdownPath)
    : outputPath(outputMarkdownPath) {
    VDB_ASSERT(!outputPath.empty(), "benchmark output path must not be empty");
    ensure_file_exists();
    DLOG("benchmark output path is '" << outputPath << "'");
}

void BenchmarkRunner::ensure_file_exists() {
    std::ifstream check(outputPath);
    if (check.good()) return; // if exists return

    std::ofstream out(outputPath);
    out << "# Benchmarks\n\n";
    out << "Auto-generated by BenchmarkRunner. Each run appends a section — "
           "prune old ones manually if a table gets noisy.\n\n";
}

std::vector<std::vector<float>> BenchmarkRunner::generate_random_vectors(size_t count, uint32_t dim, unsigned seed) {
    VDB_ASSERT(dim > 0, "random vectors need a positive dimension");
    std::mt19937 rng(seed);
    std::uniform_real_distribution<float> dist(-1.0f, 1.0f);

    std::vector<std::vector<float>> generatingVectors;
    generatingVectors.reserve(count);
    for (size_t i = 0; i < count; ++i) {
        std::vector<float> v(dim);
        for (uint32_t d = 0; d < dim; ++d) v[d] = dist(rng);
        generatingVectors.push_back(std::move(v));
    }
    return generatingVectors;
}

std::vector<std::string> BenchmarkRunner::generate_Ids(size_t count, const std::string& prefix, unsigned seed) {
    (void)seed; // ids just need to be unique not random
    std::vector<std::string> ids;
    ids.reserve(count);
    for (size_t i = 0; i < count; ++i) {
        ids.push_back(prefix + "_" + std::to_string(i));
    }
    return ids;
}

LatencyStats BenchmarkRunner::compute_stats(std::vector<double>& latenciesMs) {
    LatencyStats stats;
    stats.sampleCount = latenciesMs.size();
    if (latenciesMs.empty()) return stats;

    std::sort(latenciesMs.begin(), latenciesMs.end());

    auto percentile = [&](double p) -> double {
        double idx = p * (static_cast<double>(latenciesMs.size()) - 1.0);
        size_t lo = static_cast<size_t>(std::floor(idx));
        size_t hi = static_cast<size_t>(std::ceil(idx));
        VDB_ASSERT(lo < latenciesMs.size() && hi < latenciesMs.size(),
                   "latency percentile index is out of range");
        if (lo == hi) return latenciesMs[lo];
        double frac = idx - static_cast<double>(lo);
        return latenciesMs[lo] * (1.0 - frac) + latenciesMs[hi] * frac;
    };

    stats.p50Ms = percentile(0.50);
    stats.p95Ms = percentile(0.95);
    stats.p99Ms = percentile(0.99);
    stats.minMs = latenciesMs.front();
    stats.maxMs = latenciesMs.back();

    double sum = 0.0;
    for (double v : latenciesMs) sum += v;
    stats.avgMs = sum / static_cast<double>(latenciesMs.size());

    return stats;
}

BenchmarkResult BenchmarkRunner::run_benchmark(collection& coll,
                                                    Index& index,
                                                    const std::string& label,
                                                    size_t numVectors,
                                                    uint32_t k,
                                                    size_t numQueries,
                                                    unsigned seed) {
    if (numVectors == 0)
        throw std::invalid_argument("benchmark requires at least one query vector");
    if (numQueries == 0)
        throw std::invalid_argument("benchmark requires at least one query");
    VDB_ASSERT(coll._dim() > 0, "benchmark collection dimension must be positive");
    DLOG("running benchmark '" << label << "' with " << numVectors << " vectors and "
              << numQueries << " queries");
    BenchmarkResult result;
    result.label = label;
    result.numVectors = numVectors;
    result.dimension = coll._dim();
    result.k = k;

    auto vectors = generate_random_vectors(numVectors, coll._dim(), seed);
    auto ids = generate_Ids(numVectors, "bench_" + label, seed);
    VDB_ASSERT(vectors.size() == ids.size(), "benchmark vector/id counts do not match");

    // Query latency 
    std::mt19937 rng(seed + 1);
    std::uniform_int_distribution<size_t> pick(0, numVectors - 1);

    std::vector<double> queryLatencies;
    queryLatencies.reserve(numQueries);
    for (size_t i = 0; i < numQueries; ++i) {
        const std::vector<float>& q = vectors[pick(rng)];
        auto start = Clock::now();
        auto res = index.search(q, k);
        auto end = Clock::now();
        (void)res;
        queryLatencies.push_back(std::chrono::duration<double, std::milli>(end - start).count());
    }
    result.queryLatency = compute_stats(queryLatencies);

    result.memoryBytesEstimate = coll._memory();
    DLOG("finished benchmark '" << label << "'; p50 latency="
              << result.queryLatency.p50Ms << "ms");

    return result;
}

double BenchmarkRunner::compute_recall_at_K(const std::vector<Neighbor>& approxResults,
                                            const std::vector<Neighbor>& groundTruth,
                                            uint32_t k) {
    if (k == 0 || groundTruth.empty()) return 0.0;

    std::unordered_set<std::string> truthIds;
    size_t truthLimit = std::min<size_t>(k, groundTruth.size());
    truthIds.reserve(truthLimit);
    for (size_t i = 0; i < truthLimit; ++i) truthIds.insert(groundTruth[i].id);

    size_t hits = 0;
    size_t approxLimit = std::min<size_t>(k, approxResults.size());
    for (size_t i = 0; i < approxLimit; ++i) {
        if (truthIds.count(approxResults[i].id)) ++hits;
    }
    return static_cast<double>(hits) / static_cast<double>(truthLimit);
}

double BenchmarkRunner::average_recall_at_K(const std::vector<std::vector<Neighbor>>& approxPerQuery,
                                          const std::vector<std::vector<Neighbor>>& groundTruthPerQuery,
                                          uint32_t k) {
    if (approxPerQuery.size() != groundTruthPerQuery.size() || approxPerQuery.empty()) return 0.0;

    double sum = 0.0;
    for (size_t i = 0; i < approxPerQuery.size(); ++i) {
        sum += compute_recall_at_K(approxPerQuery[i], groundTruthPerQuery[i], k);
    }
    return sum / static_cast<double>(approxPerQuery.size());
}

void BenchmarkRunner::append_result_to_markdown(const BenchmarkResult& result) {
    std::ofstream out(outputPath, std::ios::app);
    if (!out.is_open()) return;

    double memMB = result.memoryBytesEstimate / (1024.0 * 1024.0);

    out << "### " << result.label << " (" << result.indexType << ")\n\n";
    out << "| N | dim | k | query p50 (ms) | query p95 (ms) | query p99 (ms) |  avg (ms) | "
           "recall@k | est. memory (MB) |\n";
    out << "|---|-----|---|------------------|------------------|-----------------|-----------------|"
           "----------|-------------------|\n";
    out << "| " << result.numVectors
        << " | " << result.dimension
        << " | " << result.k
        << " | " << result.queryLatency.p50Ms
        << " | " << result.queryLatency.p95Ms
        << " | " << result.queryLatency.p99Ms
        << " | " << result.queryLatency.avgMs
        << " | " << (result.recallAtK < 0.0 ? std::string("n/a") : std::to_string(result.recallAtK))
        << " | " << memMB
        << " |\n\n";

    if (!result.params.empty()) {
        out << "Params: ";
        for (size_t i = 0; i < result.params.size(); ++i) {
            out << result.params[i].first << "=" << result.params[i].second;
            if (i + 1 < result.params.size()) out << ", ";
        }
        out << "\n\n";
    }
}

void BenchmarkRunner::append_section(const std::string& heading) {
    std::ofstream out(outputPath, std::ios::app);
    if (!out.is_open()) return;
    out << "## " << heading << "\n\n";
}

void BenchmarkRunner::append_note(const std::string& note) {
    std::ofstream out(outputPath, std::ios::app);
    if (!out.is_open()) return;
    out << note << "\n\n";
}